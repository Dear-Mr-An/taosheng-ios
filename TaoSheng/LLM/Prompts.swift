    - 所有规则按意图、责任主体、动作是否完成判断，不把个别例句当作关键词黑名单。
    """

    static func digestUser(day: String,
                           lines: [String],
                           unfinished: [String] = [],
                           ignored: [String] = []) -> String {
        var s = """
        # 日历
        \(calendarTable())

        # 原话
        \(lines.joined(separator: "\n"))
        """
        if !unfinished.isEmpty {
            s += "\n\n# unfinished_items\n" + unfinished.joined(separator: "\n")
        }
        if !ignored.isEmpty {
            s += "\n\n# ignored_items\n" + ignored.joined(separator: "\n")
        }
        return s
    }

